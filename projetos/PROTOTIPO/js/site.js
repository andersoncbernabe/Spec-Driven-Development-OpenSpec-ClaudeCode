function posClass(p) {
  return { GK:'pos-gk', DF:'pos-df', MF:'pos-mf', AT:'pos-at' }[p] || 'pos-df';
}

function fmtData(iso) {
  const [y,m,d] = iso.split('-');
  const meses = ['','jan','fev','mar','abr','mai','jun','jul','ago','set','out','nov','dez'];
  return `${d} ${meses[+m]}`;
}

function fmtDataLong(iso) {
  const [y,m,d] = iso.split('-');
  const meses = ['','Janeiro','Fevereiro','Março','Abril','Maio','Junho','Julho','Agosto','Setembro','Outubro','Novembro','Dezembro'];
  const dias  = ['Domingo','Segunda-feira','Terça-feira','Quarta-feira','Quinta-feira','Sexta-feira','Sábado'];
  const dt = new Date(`${iso}T12:00:00`);
  return `${dias[dt.getDay()]}, ${d} de ${meses[+m]} de ${y}`;
}

function calcStandings(groupCode) {
  const teamCodes = GRUPOS[groupCode].teams;
  const map = {};
  teamCodes.forEach(c => { map[c] = { code:c, j:0, v:0, e:0, d:0, gp:0, gc:0, pts:0 }; });

  JOGOS.filter(g => g.grupo === groupCode && g.hG !== null && g.aG !== null)
    .forEach(g => {
      const h = map[g.home], a = map[g.away];
      if (!h || !a) return;
      h.j++; a.j++;
      h.gp += g.hG; h.gc += g.aG;
      a.gp += g.aG; a.gc += g.hG;
      if (g.hG > g.aG)      { h.v++; h.pts+=3; a.d++; }
      else if (g.hG < g.aG) { a.v++; a.pts+=3; h.d++; }
      else                   { h.e++; h.pts+=1; a.e++; a.pts+=1; }
    });

  return Object.values(map).sort((a,b) =>
    b.pts - a.pts || (b.gp-b.gc) - (a.gp-a.gc) || b.gp - a.gp
  );
}

